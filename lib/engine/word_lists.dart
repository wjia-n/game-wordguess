  static String dailyWord(int len, DateTime date) {
    final list = byLength[len] ?? _w5;
    final days = DateTime(date.year, date.month, date.day).millisecondsSinceEpoch ~/ 86400000;
    return list[days % list.length];
  }

  static String randomWord(int len, String avoid) {
    final list = byLength[len] ?? _w5;
    var w = list[(DateTime.now().microsecondsSinceEpoch ^ list.length) % list.length];
    // Cheap shuffle fallback so we rarely repeat the same word twice in a row.
    if (w == avoid && list.length > 1) {
      w = list[(list.indexOf(w) + 37) % list.length];
    }
    return w;
  }

